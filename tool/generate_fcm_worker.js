// Run after flutterfire configure. Copies only public Firebase web configuration.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const dart = fs.readFileSync(path.join(root, 'lib/firebase_options.dart'), 'utf8');
const block = dart.match(/static const FirebaseOptions web = FirebaseOptions\(([\s\S]*?)\);/);
if (!block) throw new Error('Run flutterfire configure --platforms=web first.');
const config = {};
for (const key of ['apiKey','appId','messagingSenderId','projectId','authDomain','storageBucket','measurementId']) {
  const match = block[1].match(new RegExp(`${key}:\\s*'([^']+)'`));
  if (match) config[key] = match[1];
}
if (!config.appId || !config.apiKey) throw new Error('Firebase web options are incomplete.');
fs.writeFileSync(path.join(root, 'web/firebase-messaging-sw.js'),
  `// Generated by tool/generate_fcm_worker.js. Firebase configuration is public.\n` +
  `importScripts('https://www.gstatic.com/firebasejs/12.3.0/firebase-app-compat.js');\n` +
  `importScripts('https://www.gstatic.com/firebasejs/12.3.0/firebase-messaging-compat.js');\n` +
  `firebase.initializeApp(${JSON.stringify(config, null, 2)});\n` +
  `firebase.messaging();\n`);
console.log('Generated web/firebase-messaging-sw.js');
